#!/usr/bin/env python3
"""Build the MONAD design-system token sheet from the authoritative Phase 1.1 file.

Source of truth : MONAD/brand/final/assets/tokens.json  (never hand-edited here)
Output          : MONAD/design-system/css/tokens.css  +  tokens.extended.json

Phase 1.2 documents and fills six gaps in the Phase 1.1 token file:
  weights, line-heights (numeric), borders, shadows, breakpoints, z-index,
  focus ring. They are ADDED to the authoritative file (version 1.1.0) rather
  than introduced as a second colour system.
"""
import json, os, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC  = os.path.join(ROOT, "brand", "final", "assets", "tokens.json")
OUT_CSS = os.path.join(ROOT, "design-system", "css", "tokens.css")
t = json.load(open(SRC, encoding="utf-8"))

# --- documented gaps, filled once -------------------------------------------
t["meta"]["version"] = "1.2.0"
t["meta"]["phase"] = "1.2"
t["meta"]["gapFilled"] = ["fontWeights", "lineHeights", "borders", "shadows",
                          "breakpoints", "zIndex", "focusRing", "spacingTokens"]
t["weight"] = {"regular": 400, "medium": 500, "semibold": 600, "bold": 700}
t["leading"] = {"tight": 1.25, "ui": 1.45, "base": 1.75, "loose": 2.0}
t["border"] = {"hairline": "1px solid var(--m-color-line)",
               "strong": "1px solid var(--m-color-line-strong)",
               "focus": "2px solid var(--m-color-focus)"}
t["shadow"] = {"none": "none",
               "card": "0 1px 2px rgba(0,0,0,.18), 0 8px 24px -18px rgba(0,0,0,.55)",
               "raised": "0 2px 6px rgba(0,0,0,.22), 0 18px 40px -24px rgba(0,0,0,.65)",
               "sheet": "0 -8px 40px -12px rgba(0,0,0,.55)"}
t["breakpoint"] = {"sm": "380px", "md": "600px", "lg": "900px", "xl": "1200px"}
t["z"] = {"base": 0, "raised": 10, "sticky": 20, "nav": 30, "sheet": 40,
          "modal": 50, "toast": 60, "tooltip": 70}
t["focus"] = {"width": "2px", "offset": "2px",
              "colorDark": "#E0A24B", "colorLight": "#8C5315"}
t["spaceNamed"] = {"xs": 4, "sm": 8, "md": 12, "lg": 16, "xl": 24, "2xl": 32, "3xl": 48, "4xl": 64}

# --- extra derived colours (semantic only, no new palette) -------------------
for theme, c in t["color"].items():
    c["lineStrong"] = "rgba(237,228,212,0.22)" if theme == "dark" else "rgba(26,25,23,0.22)"
    c["focus"] = t["focus"]["colorDark" if theme == "dark" else "colorLight"]
    c["overlay"] = "rgba(9,10,11,0.62)" if theme == "dark" else "rgba(26,25,23,0.38)"
    c["accentSoft"] = ("rgba(200,131,42,0.14)" if theme == "dark" else "rgba(169,102,30,0.10)")

def block(sel, colors):
    out = [sel + " {"]
    for k, v in colors.items():
        out.append(f"  --m-color-{k}: {v};")
    out.append("}")
    return out

css = ["/* MONAD design tokens 1.2.0 — generated by tools/build_tokens.py",
       "   Source of truth: MONAD/brand/final/assets/tokens.json",
       "   Components must not hard-code hex values. */", ""]
css += block(":root,\n[data-theme=\"dark\"]", t["color"]["dark"])
css += [""]
css += block('[data-theme="light"]', t["color"]["light"])
css += ["",
        "/* no-JS: follow the operating system */",
        "@media (prefers-color-scheme: light) {",
        '  [data-theme="system"], :root:not([data-theme]) {']
for k, v in t["color"]["light"].items():
    css.append(f"    --m-color-{k}: {v};")
css += ["  }", "}", ""]

css.append(":root {")
for k, v in t["weight"].items():
    css.append(f"  --m-weight-{k}: {v};")
for k, v in t["type"]["scale"].items():
    css.append(f"  --m-text-{k}: {v}px;")
for k, v in t["leading"].items():
    css.append(f"  --m-leading-{k}: {v};")
for k, v in t["spaceNamed"].items():
    css.append(f"  --m-space-{k}: {v}px;")
for k, v in t["radius"].items():
    css.append(f"  --m-radius-{k}: {v}px;")
for k, v in t["shadow"].items():
    css.append(f"  --m-shadow-{k}: {v};")
for k, v in t["z"].items():
    css.append(f"  --m-z-{k}: {v};")
for k, v in t["motion"].items():
    if isinstance(v, int):
        css.append(f"  --m-dur-{k}: {v}ms;")
css.append(f"  --m-ease: {t['motion']['easing']};")
css.append("  --m-border-hairline: 1px solid var(--m-color-line);")
css.append("  --m-border-strong: 1px solid var(--m-color-lineStrong);")
css.append("  --m-focus-width: 2px;")
css.append("  --m-focus-offset: 2px;")
css.append("  --m-font-fa: 'Vazirmatn', system-ui, sans-serif;")
css.append("  --m-font-en: 'Inter', system-ui, sans-serif;")
css.append("  --m-font-ui: var(--m-font-en);")
css.append("  --m-tap-min: 44px;")
css.append("}")
css.append('[lang="fa"], [dir="rtl"] { --m-font-ui: var(--m-font-fa); }')
css.append("")
css.append("/* breakpoints are media-query only (documented, not usable as custom props) */")
for k, v in t["breakpoint"].items():
    css.append(f"/* --m-bp-{k}: {v} */")

open(OUT_CSS, "w", encoding="utf-8").write("\n".join(css) + "\n")
json.dump(t, open(os.path.join(ROOT, "design-system", "tokens.extended.json"), "w"),
          ensure_ascii=False, indent=2)
json.dump(t, open(SRC, "w"), ensure_ascii=False, indent=2)   # authoritative stays single
print("tokens.css lines:", len(css))
print("colour tokens:", len(t["color"]["dark"]))
